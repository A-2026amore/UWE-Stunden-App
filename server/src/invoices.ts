/**
 * Invoices (migration 0019, docs/api.md) and the re-opening of approved monthly
 * statements (migration 0017):
 *
 *   POST /api/statements/:statementId/reopen                     leadership, reason ≥ 5 characters
 *   GET  /api/statements/:statementId/events                     history (employee: own; leadership)
 *   GET  /api/platform/invoice-settings                          platform staff
 *   PUT  /api/platform/invoice-settings                          super_admin, reason required
 *   GET  /api/platform/invoices[?tenantId=&month=]               platform staff (all customers)
 *   GET  /api/platform/tenants/:tenantId/invoices/:month/draft   platform staff: preview without number
 *   POST /api/platform/tenants/:tenantId/invoices/:month         super_admin: issue (number, frozen month)
 *   POST /api/platform/invoices/:invoiceId/cancel                super_admin: cancellation with own number
 *   GET  /api/tenants/:tenantId/invoices                         owner of the tenant
 *
 * Access checks, numbering, immutability and audit live in the database
 * (SECURITY DEFINER functions, RLS). The PDF is generated by the apps from the
 * returned data (platform/src/core/invoice.ts). Nothing is sent, nothing is charged.
 */
import type { Invoice, InvoiceDraft, InvoiceSettings } from "../../platform/src/core/invoice.ts";
import type { StatementEvent } from "../../platform/src/core/types.ts";
import type { AppContext } from "./app.ts";
import type { Queryable } from "./db.ts";
import { badRequest, forbidden } from "./errors.ts";
import type { Router } from "./http.ts";
import { iso, toStatement, STATEMENT_SELECT } from "./mappers.ts";
import * as v from "./validate.ts";

type Row = Record<string, unknown>;

const INVOICE_SELECT = `select i.id, i.tenant_id, i.kind, i.number, i.month,
    to_char(i.issue_date, 'YYYY-MM-DD') as issue_date, to_char(i.service_period_start, 'YYYY-MM-DD') as service_period_start,
    to_char(i.service_period_end, 'YYYY-MM-DD') as service_period_end, i.payment_terms_days,
    to_char(i.due_date, 'YYYY-MM-DD') as due_date, i.issuer, i.recipient, i.lines, i.net_cents, i.vat_rate_percent::float8 as vat_rate_percent,
    i.vat_cents, i.gross_cents, i.currency, i.vat_rate_confirmed, i.cancels_invoice_id, o.number as cancels_invoice_number,
    i.cancel_reason, i.cancelled_at, i.cancelled_by_invoice_id, i.created_at, t.name as tenant_name
  from public.invoices i
  left join public.invoices o on o.id = i.cancels_invoice_id
  left join public.tenants t on t.id = i.tenant_id`;

export function toInvoice(r: Row): Invoice {
  return {
    id: String(r.id),
    tenantId: String(r.tenant_id),
    tenantName: (r.tenant_name as string | null) ?? null,
    kind: r.kind as Invoice["kind"],
    number: String(r.number),
    month: String(r.month),
    issueDate: String(r.issue_date),
    servicePeriodStart: String(r.service_period_start),
    servicePeriodEnd: String(r.service_period_end),
    paymentTermsDays: Number(r.payment_terms_days),
    dueDate: String(r.due_date),
    issuer: r.issuer as Invoice["issuer"],
    recipient: r.recipient as Invoice["recipient"],
    lines: r.lines as Invoice["lines"],
    netCents: Number(r.net_cents),
    vatRatePercent: Number(r.vat_rate_percent),
    vatRateConfirmed: Boolean(r.vat_rate_confirmed),
    vatCents: Number(r.vat_cents),
    grossCents: Number(r.gross_cents),
    currency: "EUR",
    cancelsInvoiceId: (r.cancels_invoice_id as string | null) ?? null,
    cancelsInvoiceNumber: (r.cancels_invoice_number as string | null) ?? null,
    cancelReason: (r.cancel_reason as string | null) ?? null,
    cancelledAt: r.cancelled_at ? iso(r.cancelled_at) : null,
    cancelledByInvoiceId: (r.cancelled_by_invoice_id as string | null) ?? null,
    createdAt: iso(r.created_at),
  };
}

function toSettings(s: Row): InvoiceSettings {
  return { ...(s as unknown as InvoiceSettings), vatRatePercent: Number(s.vatRatePercent), missing: (s.missing as string[]) ?? [] };
}

async function invoiceById(q: Queryable, id: string): Promise<Invoice> {
  const r = (await q.query(`${INVOICE_SELECT} where i.id = $1`, [id])).rows[0] as Row | undefined;
  if (!r) throw forbidden("Rechnung nicht gefunden oder kein Zugriff.");
  return toInvoice(r);
}

/** Validated patch for platform_set_invoice_settings (the database checks again). */
function settingsPatch(b: v.Json): Record<string, unknown> {
  const out: Record<string, unknown> = {};
  const text = (k: string, label: string, max: number, opts: Partial<v.StrOpts> = {}) => {
    if (b[k] !== undefined) out[k] = b[k] === null ? "" : v.str(b[k], { label, max, ...opts });
  };
  text("issuerName", "Der Name des Rechnungsstellers", 200);
  text("issuerStreet", "Die Straße", 200);
  text("issuerPostalCode", "Die Postleitzahl", 10, { pattern: /^[0-9A-Za-z -]*$/ });
  text("issuerCity", "Der Ort", 120);
  text("issuerCountry", "Das Land", 80);
  text("issuerEmail", "Die E-Mail-Adresse", 254, { pattern: /^$|^[^@\s]+@[^@\s]+\.[^@\s]+$/, patternMessage: "Bitte eine gültige E-Mail-Adresse angeben." });
  text("issuerPhone", "Die Telefonnummer", 40, { pattern: /^$|^[0-9 +()/-]{3,40}$/, patternMessage: "Telefonnummer: nur Ziffern, Leerzeichen und + ( ) / -." });
  text("taxNumber", "Die Steuernummer", 40, { pattern: /^$|^.{3,40}$/, patternMessage: "Die Steuernummer muss 3–40 Zeichen lang sein." });
  text("vatId", "Die USt-IdNr.", 20, { pattern: /^$|^[A-Za-z]{2}[0-9A-Za-z+*. ]{2,15}$/, patternMessage: "Die USt-IdNr. beginnt mit dem Länderkürzel, z. B. DE123456789." });
  text("paymentDetails", "Die Zahlungshinweise", 500);
  text("numberPrefix", "Das Präfix der Rechnungsnummer", 6, { min: 1, pattern: /^[A-Za-z]{1,6}$/, patternMessage: "Präfix: 1–6 Buchstaben, z. B. SW." });
  if (b.vatRatePercent !== undefined) {
    const n = b.vatRatePercent;
    if (typeof n !== "number" || !Number.isFinite(n) || n < 0 || n > 100 || Math.round(n * 100) !== n * 100) {
      throw badRequest("Der USt-Satz muss zwischen 0 und 100 % liegen (höchstens zwei Nachkommastellen).");
    }
    out.vatRatePercent = n;
  }
  if (b.vatRateConfirmed !== undefined) out.vatRateConfirmed = v.bool(b.vatRateConfirmed, "USt-Satz bestätigt");
  if (b.paymentTermsDays !== undefined) out.paymentTermsDays = v.int(b.paymentTermsDays, "Zahlungsziel (Tage)", 0, 120);
  return out;
}

export function registerInvoiceRoutes(router: Router, app: AppContext): void {
  const json = (status: number, body: unknown) => ({ status, body });

  // ---------------------------------------------------------------- statements: re-open and history (0017)
  router.add("POST", "/api/statements/:statementId/reopen", async (ctx) => {
    const id = v.uuid(ctx.params.statementId, "Abrechnungs-ID");
    const b = v.object(ctx.body, ["reason"]);
    const reason = v.reason(b.reason, 5, "Bitte begründen, warum der freigegebene Monat wieder geöffnet wird (mind. 5 Zeichen).");
    return app.asUser(ctx, async (q) => {
      const r = (await q.query("select * from public.reopen_statement($1, $2)", [id, reason])).rows[0] as Row;
      const full = (await q.query(`${STATEMENT_SELECT} where s.id = $1`, [r.id])).rows[0] as Row;
      return json(200, toStatement(full));
    });
  });

  router.add("GET", "/api/statements/:statementId/events", async (ctx) => {
    const id = v.uuid(ctx.params.statementId, "Abrechnungs-ID");
    return app.asUser(ctx, async (q) => {
      const st = (await q.query("select id from public.monthly_statements where id = $1", [id])).rows[0];
      if (!st) throw forbidden("Monatsnachweis nicht gefunden oder kein Zugriff.");
      const rows = (await q.query(
        `select ev.action, ev.created_at, ev.reason, ev.worked_minutes, ev.allocated_minutes, ev.billing_minutes, a.display_name as actor_name
           from public.monthly_statement_events ev
           left join public.employees a on a.user_id = ev.actor_id and a.tenant_id = ev.tenant_id
          where ev.statement_id = $1 order by ev.created_at, ev.id`, [id])).rows as Row[];
      const events: StatementEvent[] = rows.map((r) => ({
        action: r.action as StatementEvent["action"], at: iso(r.created_at), actorName: (r.actor_name as string | null) ?? null,
        reason: (r.reason as string | null) ?? null, workedMinutes: Number(r.worked_minutes),
        allocatedMinutes: Number(r.allocated_minutes), billingMinutes: Number(r.billing_minutes),
      }));
      return json(200, events);
    });
  });

  // ---------------------------------------------------------------- invoice settings
  router.add("GET", "/api/platform/invoice-settings", async (ctx) =>
    app.asUser(ctx, async (q) => json(200, toSettings((await q.query("select public.platform_invoice_settings() as s")).rows[0].s as Row))));

  router.add("PUT", "/api/platform/invoice-settings", async (ctx) => {
    const b = v.object(ctx.body, ["issuerName", "issuerStreet", "issuerPostalCode", "issuerCity", "issuerCountry", "issuerEmail",
      "issuerPhone", "taxNumber", "vatId", "paymentDetails", "vatRatePercent", "vatRateConfirmed", "paymentTermsDays", "numberPrefix", "reason"]);
    const reason = v.reason(b.reason, 3, "Bitte einen Grund für die Änderung angeben.");
    const patch = settingsPatch(b);
    return app.asUser(ctx, async (q) =>
      json(200, toSettings((await q.query("select public.platform_set_invoice_settings($1::jsonb, $2) as s", [JSON.stringify(patch), reason])).rows[0].s as Row)));
  });

  // ---------------------------------------------------------------- invoices (platform)
  router.add("GET", "/api/platform/invoices", async (ctx) => {
    const tenantId = ctx.query.get("tenantId");
    const month = ctx.query.get("month");
    const params: unknown[] = [];
    const where: string[] = [];
    if (tenantId) { params.push(v.uuid(tenantId, "Mandanten-ID")); where.push(`i.tenant_id = $${params.length}`); }
    if (month) { params.push(v.month(month)); where.push(`i.month = $${params.length}`); }
    return app.asUser(ctx, async (q) => {
      const ok = (await q.query("select private.is_platform_admin() as ok")).rows[0]?.ok;
      if (!ok) throw forbidden("Nur für die Plattformverwaltung.");
      const rows = (await q.query(`${INVOICE_SELECT} ${where.length ? "where " + where.join(" and ") : ""} order by i.year desc, i.seq desc limit 1000`, params)).rows as Row[];
      return json(200, rows.map(toInvoice));
    });
  });

  router.add("GET", "/api/platform/tenants/:tenantId/invoices/:month/draft", async (ctx) => {
    const id = v.uuid(ctx.params.tenantId, "Mandanten-ID");
    const month = v.month(ctx.params.month);
    return app.asUser(ctx, async (q) => {
      const d = (await q.query("select public.platform_invoice_draft($1, $2) as d", [id, month])).rows[0].d as Row;
      return json(200, { ...d, vatRatePercent: Number(d.vatRatePercent) } as unknown as InvoiceDraft);
    });
  });

  router.add("POST", "/api/platform/tenants/:tenantId/invoices/:month", async (ctx) => {
    const id = v.uuid(ctx.params.tenantId, "Mandanten-ID");
    const month = v.month(ctx.params.month);
    v.object(ctx.body, []);
    return app.asUser(ctx, async (q) => {
      const r = (await q.query("select id from public.platform_issue_invoice($1, $2)", [id, month])).rows[0] as Row;
      return json(201, await invoiceById(q, String(r.id)));
    });
  });

  router.add("POST", "/api/platform/invoices/:invoiceId/cancel", async (ctx) => {
    const id = v.uuid(ctx.params.invoiceId, "Rechnungs-ID");
    const b = v.object(ctx.body, ["reason"]);
    const reason = v.reason(b.reason, 5, "Bitte einen Grund für das Storno angeben (mind. 5 Zeichen).");
    return app.asUser(ctx, async (q) => {
      const r = (await q.query("select id from public.platform_cancel_invoice($1, $2)", [id, reason])).rows[0] as Row;
      return json(201, await invoiceById(q, String(r.id)));
    });
  });

  // ---------------------------------------------------------------- invoices (customer: owner)
  router.add("GET", "/api/tenants/:tenantId/invoices", async (ctx) => {
    const id = v.uuid(ctx.params.tenantId, "Mandanten-ID");
    return app.asUser(ctx, async (q) => {
      const ok = (await q.query("select private.is_owner($1) as ok", [id])).rows[0]?.ok;
      if (!ok) throw forbidden("Rechnungen sieht nur der Inhaber des Mandanten.");
      const rows = (await q.query(`${INVOICE_SELECT} where i.tenant_id = $1 order by i.year desc, i.seq desc`, [id])).rows as Row[];
      return json(200, rows.map(toInvoice));
    });
  });
}
